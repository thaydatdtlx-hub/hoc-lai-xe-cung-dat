import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {studentNotifications} from "../account-notifications.js";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const slot={id:"fixture-1",session_type:"practice",status:"open",starts_at:"2099-11-28T06:00:00Z",ends_at:"2099-11-28T10:00:00Z",duration_minutes:240,available_count:4,location:"Sân tập"};
const learner={name:"Học viên thử",training_requests:[],training_sessions:[]};
const invites=(s,slots)=>studentNotifications(s,slots).filter(n=>n.id.startsWith("training-slot-invite:"));
const first=invites(learner,[slot]);
assert.equal(first.length,1);
assert.equal(first[0].action,"Đăng ký ngay");
assert.ok(first[0].body.includes("13:00 – 17:00")&&first[0].href.includes("training_slot=fixture-1"));
assert.equal(invites(learner,[{...slot,available_count:0},{...slot,status:"closed"},{...slot,student_registered:true}]).length,0);
assert.equal(invites({...learner,training_requests:[{slot_id:slot.id,status:"pending"}]},[slot]).length,0);
assert.equal(invites({...learner,training_sessions:[{slot_id:slot.id}]},[slot]).length,0);
const sql=read("supabase/migrations/20261125_training_slot_invites.sql");
assert.ok(sql.includes("s.id=any(v_slot.allowed_student_ids)")&&sql.includes("a.account_type='student'")&&sql.includes("on conflict(recipient_kind,recipient_id,notification_key)")&&sql.includes("perform private.app_send_training_slot_invites(v_id)"));
assert.ok(read("student.js").includes("openInvitedTrainingSlot")&&read("student.js").includes("serverIds.has(notice.id)"));
console.log("PASS: thông báo mời đăng ký theo ca, đúng giờ Việt Nam, không mời khi hết chỗ hoặc đã đăng ký, liên kết mở đúng ca.");
