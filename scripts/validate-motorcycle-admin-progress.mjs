import{readFileSync}from"node:fs";
import{strict as assert}from"node:assert";
const js=readFileSync(new URL("../app.js",import.meta.url),"utf8");
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const start=js.indexOf("function progressHtml(s){");
const end=js.indexOf("\nfunction ",start+12);
const renderer=js.slice(start,end);
assert(start>=0&&end>start,"Missing progress render function");
assert.match(renderer,/if\(isMotorcycleLicense\(s\.license_class\)\)\{/);
const moto=renderer.slice(renderer.indexOf("if(isMotorcycleLicense"),renderer.indexOf("const dates="));
assert.match(moto,/<b>Sát hạch<\/b>/);
for(const stage of ["Online","Cabin","DAT","Tốt nghiệp"])assert(!moto.includes("<b>"+stage+"</b>"),"Motorcycle row must not show "+stage);
const car=renderer.slice(renderer.indexOf("const dates="));
for(const stage of ["Online","Cabin","DAT","Tốt nghiệp","Sát hạch"])assert(car.includes("<b>"+stage+"</b>"),"Car progress lost "+stage);
assert.match(js,/const MOTORCYCLE_LICENSES=new Set\(\["A1","A"\]\)/);
assert.match(js,/const MOTORCYCLE_HIDDEN_STUDENT_FIELDS=\["onlineStatus","onlineStart","onlineEnd","cabinStatus","datStatus","graduationStatus"\]/);
assert.match(html,/>Học lý thuyết<\/th>/);
assert.match(js,/const bankTotal=isMotorcycleLicense\(student\.license_class\)\?250:600/);
console.log("Đạt: A1/A chỉ hiển thị Sát hạch; B/C1 giữ 5 giai đoạn, biểu mẫu xe máy ẩn 4 mục, tiến độ 250/600 đúng hạng.");
